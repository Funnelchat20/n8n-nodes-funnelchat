function successSchema(doc, op) {
	for (const [code, response] of Object.entries(op.responses ?? {})) {
		if (!code.startsWith('2')) continue;
		const r = deref(doc, response);
		const content = r?.content?.['application/json'];
		if (content?.schema) return content.schema;
	}
	return undefined;
}

function listInfo(doc, op, method, queryNames) {
	if (method !== 'GET') return undefined;
	const schema = successSchema(doc, op);
	if (!schema) return undefined;
	const variants = variantsOf(doc, schema);
	const hasItems = variants.some((v) => {
		if (typeOf(v) === 'array') return true;
		const data = v.properties?.data ? normalize(doc, v.properties.data) : undefined;
		return typeOf(data) === 'array';
	});
	if (!hasItems) return undefined;

	const metaOf = (v) => (v.properties?.meta ? normalize(doc, v.properties.meta) : undefined);
	const listing = op['x-fc-listing'];
	const cursor =
		variants.some((v) => metaOf(v)?.properties?.next_cursor || v.properties?.next_cursor) ||
		queryNames.has('cursor');
	const page =
		variants.some((v) => metaOf(v)?.properties?.last_page || metaOf(v)?.properties?.current_page) ||
		queryNames.has('page') ||
		Boolean(listing);
	const pagination = cursor ? 'cursor' : page ? 'page' : 'none';
	if (pagination === 'none') return { pagination };

	const sizeParam =
		listing?.size_params?.[0] ?? SIZE_PARAM_CANDIDATES.find((n) => queryNames.has(n)) ?? 'perPage';
	const maxPageSize = Number(listing?.per_page_max) || 100;
	return {
		pagination,
		sizeParam,
		maxPageSize,
		ignore: new Set([...(listing?.size_params ?? []), sizeParam]),
	};
}

/** Added to the description of an irreversible operation: it is what an AI agent that uses the node as a tool reads. */
const CONFIRM_FIRST = 'Irreversible: ask for confirmation before running it.';

/** The English name and purpose of an operation: by operationId, or by `METHOD /path` for one that has none. */
function englishOf(ctx, operationId, httpMethod, path) {
	return ctx.translations[operationId] ?? ctx.translations[`${httpMethod} ${path}`];
}

function buildOperation(ctx, doc, path, method, op, resource, category) {
	const { config, warnings, review } = ctx;
	const operationId = op.operationId ?? `${method}${path.replace(/[^A-Za-z0-9]+/g, '_')}`;
	const httpMethod = method.toUpperCase();

	const rawParams = [...(doc.paths[path].parameters ?? []), ...(op.parameters ?? [])].map((p) =>
		deref(doc, p),
	);
	// Query fields the domain's code reads and its specification does not list (`extraParameters` in the config).
	for (const extra of config.extraParameters?.[operationId] ?? []) {
		if (rawParams.some((p) => p.name === extra.name && p.in === extra.in)) {
			warnings.push(
				`${operationId}: the specification already has ${extra.name}; remove it from extraParameters`,
			);
			continue;
		}
		rawParams.push(extra);
	}
	const queryNames = new Set(rawParams.filter((p) => p.in === 'query').map((p) => p.name));
	const list = listInfo(doc, op, httpMethod, queryNames);
	const pagerParams = new Set();
	if (list && list.pagination !== 'none') {
		for (const n of list.ignore) pagerParams.add(n);
		pagerParams.add(list.pagination === 'cursor' ? 'cursor' : 'page');
	}

	const used = new Set();
	const uniqueName = (apiName, location, topLevel) => {
		let name = sanitizeName(apiName);
		if (used.has(name)) name = `${location}_${name}`;
		if (topLevel && RESERVED_NAMES.has(name)) name = `${name}Value`;
		while (used.has(name)) name = `${name}_`;
		used.add(name);
		return name;
	};

	const params = [];
	for (const p of rawParams) {
		if (p.in !== 'path' && p.in !== 'query') continue;
		if (p.in === 'query' && pagerParams.has(p.name)) continue;
		const schema = p.schema ?? {};
		const required = p.in === 'path' ? true : Boolean(p.required);
		const field =
			p.in === 'path'
				? {
						kind: 'string',
						valueType: typeOf(normalize(doc, schema)) === 'integer' ? 'integer' : 'string',
					}
				: keptField(ctx, operationId, p.name, fieldFor(doc, schema));
		const description = describeField(
			ctx,
			operationId,
			{ description: p.description ?? normalize(doc, schema).description },
			p.name,
			field.kind,
		);
		params.push({
			name: uniqueName(p.name, p.in, required),
			apiName: p.name,
			location: p.in,
			required,
			kind: field.kind,
			displayName: labelFor(config, operationId, p.name),
			description,
			...(field.valueType ? { valueType: field.valueType } : {}),
			...(field.format ? { format: field.format } : {}),
			...(field.options ? { options: field.options } : {}),
		});
	}

	let body;
	if (op.requestBody) {
		const rb = deref(doc, op.requestBody);
		const content = rb.content?.['application/json'] ?? Object.values(rb.content ?? {})[0];
		const schema = normalize(doc, content?.schema ?? {});
		if (typeOf(schema) === 'array') {
			body = { required: Boolean(rb.required), root: 'array' };
			const items = normalize(doc, schema.items ?? {});
			const keys = Object.keys(items.properties ?? {});
			params.push({
				name: uniqueName('body', 'body', true),
				apiName: '',
				location: 'body',
				required: true,
				kind: 'body',
				displayName: 'Items (JSON)',
				description: `JSON list of objects${keys.length ? ` with ${keys.join(', ')}` : ''}.`,
			});
		} else {
			body = { required: Boolean(rb.required), root: 'object' };
			const required = new Set(schema.required ?? []);
			for (const [prop, propSchema] of Object.entries(schema.properties ?? {})) {
				const field = keptField(ctx, operationId, prop, fieldFor(doc, propSchema));
				const isRequired = required.has(prop);
				params.push({
					name: uniqueName(prop, 'body', isRequired),
					apiName: prop,
					location: 'body',
					required: isRequired,
					kind: field.kind,
					displayName: labelFor(config, operationId, prop),
					description: describeField(
						ctx,
						operationId,
						normalize(doc, propSchema),
						prop,
						field.kind,
					),
					...(field.valueType ? { valueType: field.valueType } : {}),
					...(field.format ? { format: field.format } : {}),
					...(field.options ? { options: field.options } : {}),
				});
			}
		}
	}

	const notices = [];
	// `:operate` routes are irreversible unless the specification says otherwise: accounts also puts there the ones that
	// give control of a number (create one, its QR, connect links), with `x-fc-destructive: false`.
	// Without the flag, only accounts:operate means irreversible (its gate says so); communities:operate is any action
	// on a group in WhatsApp, such as creating one.
	const destructive =
		op['x-fc-destructive'] === true ||
		(op['x-fc-destructive'] === undefined && op['x-fc-permission'] === 'accounts:operate');
	if (destructive) {
		notices.push(
			String(op['x-fc-permission'] ?? '').endsWith(':operate')
				? `Irreversible operation: needs the ${op['x-fc-permission']} permission.`
				: 'Irreversible operation.',
		);
	}
	const flag = op['x-portal-v0'];
	// The portal note of a flag whose notice is empty is out of date too (it is the same note), so it is dropped.
	const specNote =
		op['x-fc-nota'] ?? (PORTAL_FLAG_NOTES[flag] === '' ? undefined : portalNote(op.description));
	// The notes of the specification are in Spanish: a new one is listed, to be written in English in `operationNotes`.
	if (specNote && !config.operationNotes?.[operationId])
		review.push(
			`${operationId}: the specification has a note; add it in English to operationNotes`,
		);
	if (flag && PORTAL_FLAG_NOTES[flag]) notices.push(PORTAL_FLAG_NOTES[flag]);
	if (flag && !(flag in PORTAL_FLAG_NOTES))
		warnings.push(`${operationId}: x-portal-v0 "${flag}" without a known note`);
	// What the code of a domain requires and its specification does not say (checked by reading the code).
	const extra = config.operationNotes?.[operationId];
	if (extra) notices.push(cleanText(extra));

	const permission = op['x-fc-permission'] ?? null;
	// The specification's texts are in Spanish: the operations take their name and purpose from the translations. One
	// without them shows its route, which is neutral, and is listed to be translated.
	const english = englishOf(ctx, operationId, httpMethod, path);
	if (!english)
		review.push(
			`${operationId} (${httpMethod} ${path}) has no English name and purpose in ${TRANSLATIONS_PATH}: the node shows its route`,
		);
	const name = cleanText(english?.name ?? `${httpMethod} ${path}`);
	const purpose = english ? firstSentences(english.purpose ?? '') : '';
	const description = [
		purpose,
		permission ? `Permission: ${permission}.` : '',
		destructive ? CONFIRM_FIRST : '',
	]
		.filter(Boolean)
		.join(' ');

	// Sorting keeps the generated parameters stable and in the order the node shows them.
	// `topLevelFields` in the config: optional fields shown as fields of their own, after the required ones and in the
	// config's order, instead of inside "Filters" or "Additional Fields". A field that was required and stops being so
	// stays where saved workflows have its value; a new way of doing something can be the first thing the node shows.
	const topLevel = config.topLevelFields?.[operationId] ?? [];
	for (const name of topLevel) {
		const param = params.find((p) => p.apiName === name && p.location !== 'path');
		if (!param)
			warnings.push(`${operationId}: topLevelFields names ${name}, which it does not have`);
		else if (!param.required) param.topLevel = true;
	}
	const order = (p) =>
		p.location === 'path'
			? 0
			: p.required || p.topLevel
				? p.location === 'query'
					? 1
					: 2
				: p.location === 'query'
					? 3
					: 4;
	const within = (p) => (p.topLevel ? 1 + topLevel.indexOf(p.apiName) : 0);
	params.sort((a, b) => order(a) - order(b) || within(a) - within(b));

	// The value saved workflows use is the operationId the node published first: when the specification renames an
	// operation, `keepOperationValues` maps its new operationId to the old value, so those workflows keep working.
	const kept = config.keepOperationValues?.[operationId];

	return {
		resource,
		value: kept ?? operationId,
		...(kept ? { operationId } : {}),
		name,
		description,
		method: httpMethod,
		path,
		permission,
		...(category ? { category } : {}),
		...(notices.length ? { notice: notices.join(' ') } : {}),
		...(list
			? {
					list: {
						pagination: list.pagination,
						...(list.sizeParam ? { sizeParam: list.sizeParam } : {}),
						maxPageSize: list.maxPageSize ?? 100,
					},
				}
			: {}),
		...(body ? { body } : {}),
		params,
	};
}

